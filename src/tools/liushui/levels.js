/**
 * 按 0 基下标取关卡。
 *
 * 【为什么改成 0 基】原版 APK 的 UI 是 1..14，所以这里原本写成
 *   `LEVELS[index - 1]`，是 1 基的。但小程序里所有调用方
 *   （gotoLevel、onReset、syncChrome）用的都是 0 基下标，
 *   于是每一关都错位一格：
 *     gotoLevel(1) → levelAt(1) → LEVELS[0] = 第一关
 *     gotoLevel(2) → levelAt(2) → LEVELS[1] = 第二关
 *   表现就是「第一关点下一关还是第一关，后面的关卡正常」——
 *   因为第 0 号和第 1 号都被映射到了第一关，看起来像卡住。
 *
 *   两个下标体系混用是这类 bug 的常见来源，所以这里统一成 0 基，
 *   和数组、和所有调用方保持一致。1 基只保留在关卡数据的
 *   `index` 字段和界面上「第 N 关」的文案里，纯展示用。
 */
export function levelAt(index) {
  const i = Math.max(0, Math.min(LEVELS.length - 1, Number(index) || 0));
  return LEVELS[i];
}

export default { LEVELS, LEVEL_COUNT, levelAt };
